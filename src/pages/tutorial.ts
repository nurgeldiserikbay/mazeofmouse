/**
 * Обучающие лабиринты перед первой игрой.
 *
 * Главное правило игры неочевидно: мышь бежит сама и берёт следующую стрелку
 * только у стены или на развилке. Новичок жмёт стрелку на каждую клетку пути,
 * проигрывает и не понимает почему. Два маленьких лабиринта показывают правило
 * на деле, а игрок нажимает ровно те кнопки, которые подсвечены.
 *
 * Подсказки без текста: рука на нужной кнопке и путь мыши на поле. Так
 * обучение одинаково понятно на любом языке и ребёнку, который не читает.
 *
 * Координаты как в game.ts: maze[row][col], 0 — проход, 1 — стена. Старт
 * всегда (0,0), выход — правый нижний угол, как в обычных лабиринтах.
 */
export interface I_TutorialStep {
	maze: number[][]
	/** Стрелки, которые игрок должен набрать, по порядку. */
	dirs: string[]
	/** Клетка, на которую надо обратить внимание: [col, row]. */
	mark?: [number, number]
}

